// @ts-nocheck
import { contextBridge, ipcRenderer } from 'electron';

contextBridge.exposeInMainWorld('electronAPI', {
  handleQuery: (callback: (data: any) => void) => ipcRenderer.on('query', (_event, data) => callback(data)),
  handleExtraLoad: (callback: (data: any) => void) => ipcRenderer.on('extra_load', (_event, data) => callback(data)),
  handleOptions: (callback: (data: any) => void) => ipcRenderer.on('options', (_event, data) => callback(data)),
  handleClear: (callback: (value: any) => void) => ipcRenderer.on('clear', (_event, value) => callback(value)),
  initInfo: (callback: (info: any) => void) => ipcRenderer.on('init-info', (_event, info) => callback(info)),
  setPrompt: (callback: (prompt: any) => void) => ipcRenderer.on('prompt', (_event, prompt) => callback(prompt)),
  handleLog: (callback: (log: any) => void) => ipcRenderer.on('log', (_event, log) => callback(log)),
  send: (channel: string, data: any) => ipcRenderer.send(channel, data),
  handleMarkDownFormat: (callback: (status: any) => void) => ipcRenderer.on('markdown-format', (_event, markdown_statu) => callback(markdown_statu)),
  handleReactStatu: (callback: (status: any) => void) => ipcRenderer.on('react-statu', (_event, react_statu) => callback(react_statu)),
  queryText: (data: any) => ipcRenderer.invoke('query-text', data),
  getFilePath: () => ipcRenderer.invoke('get-file-path'),
  changeMode: (mode: any) => ipcRenderer.send('change-mode', mode),
  handleChangeMode: (callback: (mode: any) => void) => ipcRenderer.on('change-mode', (_event, mode) => callback(mode)),
  clickSubmit: (formData: any) => ipcRenderer.send('submit', formData),
  openExternal: (href: string) => ipcRenderer.send('open-external', href),
  captureRegion: (params: any) => ipcRenderer.invoke('capture-region', params),
  toggleMessage: (data: any) => ipcRenderer.invoke('toggle-message', data),
  compressionMessage: (data: any) => ipcRenderer.invoke('compression-message', data),
  thumbMessage: (data: any) => ipcRenderer.invoke('thumb-message', data),
  toggleMemory: (context_id: any) => ipcRenderer.invoke('toggle-memory', context_id),
  handleDeleteMemory: (callback: (data: any) => void) => ipcRenderer.on('delete-memory', (_event, data) => callback(data)),
  toggleAutoOpt: () => ipcRenderer.send('toggle-auto-opt'),
  streamMessageStop: () => ipcRenderer.send('stream-message-stop'),
  streamData: (callback: (chunk: any) => void) => ipcRenderer.on('stream-data', (_event, chunk) => callback(chunk)),
  infoData: (callback: (info: any) => void) => ipcRenderer.on('info-data', (_event, info) => callback(info)),
  userData: (callback: (info: any) => void) => ipcRenderer.on('user-data', (_event, info) => callback(info)),
  uploadProgress: (callback: (info: any) => void) => ipcRenderer.on('upload-progress', (_event, info) => callback(info)),
  newChat: () => ipcRenderer.invoke('new-chat'),
  handleNewChat: (callback: (chat: any) => void) => ipcRenderer.on('new-chat', (_event, chat) => callback(chat)),
  handleSelectChat: (callback: (chat: any) => void) => ipcRenderer.on('select-chat', (_event, chat) => callback(chat)),
  delChat: (id: any) => ipcRenderer.send('del-chat', id),
  loadChat: (id: any) => ipcRenderer.invoke('load-chat', id),
  handleSetChat: (callback: (chat: any) => void) => ipcRenderer.on('set-chat', (_event, chat) => callback(chat)),
  renameChat: (data: any) => ipcRenderer.send('rename-chat', data),
  getConfig: () => ipcRenderer.invoke('get-config-main'),
  setConfig: (config: any) => ipcRenderer.invoke('set-config-main', config),
  setGlobal: (chat: any) => ipcRenderer.send('set-global', chat),
  handleAutoRenameChat: (callback: (chat: any) => void) => ipcRenderer.on('auto-rename-chat', (_event, chat) => callback(chat)),
  Envs: (data: any) => ipcRenderer.invoke('envs', data),
  Tasks: (data: any) => ipcRenderer.invoke('tasks', data),
  showLog: (data: any) => ipcRenderer.send('show-log', data),
});